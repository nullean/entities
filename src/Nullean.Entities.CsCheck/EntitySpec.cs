// Nullean.Entities.CsCheck — EntitySpec<T>: a ConstraintSet<T> plus an entity's actions, handed to
// CsCheck's Spec<S> engine.
//
// An entity here is an immutable value whose mutations return a new value (Order.Confirm()), i.e. a
// pure state machine. CsCheck's Spec<S> explores such machines exhaustively, by random walk, by
// mutation (Faults), and against a real implementation (Conform). This file translates the
// constraints into Spec requirements so each of those is one call:
//
//   PointInTime constraint        -> Invariant           (holds in every state)
//   Sequential constraint         -> Rule over each step (skipped when a step changed nothing,
//                                    matching ConstraintSet.Apply's Noop short-circuit)
//   When(guard).Requires(...)     -> Rule(when: guard)   (so "guard never true" is reported)
//   Transitions(...).Allow(a, b)  -> one Rule per legal edge  (so "edge never taken" is reported)
//
// With nothing configured, AutoBogus supplies what is missing: starting states (valid ones, from fixed
// seeds) and the values every argument-taking action is tried with — see AutoDefaults.cs.

using System.Globalization;
using CsCheck;

namespace Nullean.Entities.CsCheck;

/// <summary>A state wrapper whose equality comes from a key projection, so CsCheck can tell when it has seen a state before.</summary>
internal readonly struct Keyed<T>(T value, Func<T, object?> key) : IEquatable<Keyed<T>>
{
	public T Value { get; } = value;

	public bool Equals(Keyed<T> other) => object.Equals(key(Value), key(other.Value));

	public override bool Equals(object? obj) => obj is Keyed<T> other && Equals(other);

	public override int GetHashCode() => key(Value)?.GetHashCode() ?? 0;
}

/// <summary>One step of a walk: the action taken, its argument, and the entity before and after.</summary>
public sealed record EntityStep<T>(string Action, string Argument, object? ArgumentValue, T Before, T After);

public static class EntitySpec
{
	/// <summary>A spec for a type that declares its own constraints (<c>EntitySpec.For&lt;Order&gt;()</c>), with generated starting states.</summary>
	public static EntitySpec<T> For<T>() where T : IHaveConstraints<T> => For(T.Constraints, T.Actions);

	/// <summary>A spec for a type that declares its own constraints, starting from <paramref name="initial"/>.</summary>
	public static EntitySpec<T> For<T>(T initial) where T : IHaveConstraints<T> => For(T.Constraints, T.Actions, initial);

	/// <summary>
	/// A spec whose starting states are AutoBogus-generated entities that already satisfy
	/// <paramref name="constraints"/> (three, from fixed seeds; replace them with <c>From(...)</c>).
	/// </summary>
	public static EntitySpec<T> For<T>(ConstraintSet<T> constraints, EntityActions<T>? actions) => new(constraints, null, actions);

	/// <summary>A spec starting from <paramref name="initial"/>.</summary>
	public static EntitySpec<T> For<T>(ConstraintSet<T> constraints, EntityActions<T>? actions, T initial) => new(constraints, [initial], actions);
}

public static class ConstraintSetSpecExtensions
{
	/// <summary>
	/// Starts an <see cref="EntitySpec{T}"/>: the set's constraints become requirements over every state
	/// and step reachable from <paramref name="initial"/> through <paramref name="actions"/> (generated
	/// next to the constraint set as <c>Actions</c>).
	/// </summary>
	public static EntitySpec<T> Spec<T>(this ConstraintSet<T> constraints, T initial, EntityActions<T>? actions = null) =>
		EntitySpec.For(constraints, actions, initial);

	/// <summary>
	/// <c>OrderConstraints.Instance.Spec()</c>: constraints and actions from the generated companion,
	/// starting states generated by AutoBogus.
	/// </summary>
	public static EntitySpec<T> Spec<T>(this IConstraintsFor<T> companion) => EntitySpec.For(companion.All, companion.Actions);

	/// <summary><c>OrderConstraints.Instance.Spec(initial)</c>: as above, starting from <paramref name="initial"/>.</summary>
	public static EntitySpec<T> Spec<T>(this IConstraintsFor<T> companion, T initial) => EntitySpec.For(companion.All, companion.Actions, initial);
}

public sealed class EntitySpec<T>
{
	private sealed record ActionDef(string Name, Type? ArgumentType, Func<T, object?, T> Apply, object[]? OwnDomain);

	private sealed class FixedTimeProvider(DateTimeOffset now) : TimeProvider
	{
		public override DateTimeOffset GetUtcNow() => now;
	}

	private readonly ConstraintSet<T> _constraints;
	private List<T>? _starts;
	private readonly List<ActionDef> _actions = [];
	private readonly Dictionary<Type, object[]> _domains = [];
	private readonly Dictionary<Type, (Type Source, Func<object, object> Project)> _derived = [];
	private readonly Dictionary<Type, object[]> _resolved = [];
	private readonly List<(string Id, Func<T, bool> Holds)> _reachable = [];
	private readonly List<(string Name, string? On, Func<T, T, T> Perturb)> _faults = [];
	private readonly List<(string Action, ConstraintSet<T> Set)> _scoped = [];
	private Func<T, object?> _key = v => StructuralKey.Of(v);
	private Func<T, string> _print = v => Convert.ToString(v, CultureInfo.InvariantCulture) ?? "null";
	private Func<T, bool>? _boundary;
	private Func<T, bool>? _terminal;
	private int _collectionLimit = 2;
	private AutoMode? _data;
	private bool _enforced;
	private TimeProvider _clock = new FixedTimeProvider(new DateTimeOffset(2026, 1, 1, 12, 0, 0, TimeSpan.Zero));

	internal EntitySpec(ConstraintSet<T> constraints, List<T>? starts, EntityActions<T>? actions)
	{
		_constraints = constraints;
		_starts = starts;
		if (actions is not null)
		{
			foreach (var a in actions)
			{
				_actions.Add(new ActionDef(a.Name, a.ArgumentType, a.Apply, null));
			}
		}
	}

	/// <summary>Replaces the starting states. Each is explored in turn.</summary>
	public EntitySpec<T> From(params T[] starts)
	{
		_starts = [.. starts];
		return this;
	}

	/// <summary>An action with no argument.</summary>
	public EntitySpec<T> Action(string name, Func<T, T> apply)
	{
		_actions.Add(new ActionDef(name, null, (s, _) => apply(s), null));
		return this;
	}

	/// <summary>An action over a small, finite set of arguments — each is tried from every state.</summary>
	public EntitySpec<T> Action<TArg>(string name, TArg[] domain, Func<T, TArg, T> apply)
	{
		_actions.Add(new ActionDef(name, typeof(TArg), (s, a) => apply(s, (TArg)a!), [.. domain.Cast<object>()]));
		return this;
	}

	/// <summary>
	/// The values every action taking a <typeparamref name="TArg"/> is tried with, replacing the three
	/// AutoBogus-generated ones used by default. Keep it small: the reachable state space grows with it.
	/// </summary>
	public EntitySpec<T> Domain<TArg>(params TArg[] values)
	{
		_domains[typeof(TArg)] = [.. values.Cast<object>()];
		return this;
	}

	/// <summary>
	/// Derives the <typeparamref name="TArg"/> domain from another type's: <c>DomainFrom&lt;OrderLine, string&gt;(l =&gt; l.Sku)</c>
	/// makes <c>RemoveLine(sku)</c> try the SKUs of the lines <c>AddLine</c> adds. A random string never
	/// matches existing state, which would leave the action a silent no-op.
	/// </summary>
	public EntitySpec<T> DomainFrom<TSource, TArg>(Func<TSource, TArg> project)
	{
		_derived[typeof(TArg)] = (typeof(TSource), o => project((TSource)o)!);
		return this;
	}

	/// <summary>
	/// What makes two entities "the same state". The default compares public properties structurally
	/// (collections element by element), which closes the space for most records. Replace it when only
	/// part of the state matters: <c>.Key(o => (o.Status, o.Lines.Count))</c>.
	/// </summary>
	public EntitySpec<T> Key(Func<T, object?> key)
	{
		_key = key;
		return this;
	}

	/// <summary>
	/// The largest collection (a record's list, anywhere inside it) a state may hold before it is no
	/// longer expanded. Default 2: it turns "add a line forever" into a finite space. The claim made is
	/// then "nothing breaks within this limit"; raise it for a wider search.
	/// </summary>
	public EntitySpec<T> Limit(int collections)
	{
		_collectionLimit = collections;
		return this;
	}

	/// <summary>
	/// Models an entity whose methods are deliberately plain and whose constraints are enforced at the
	/// boundary, the way <c>ConstraintSet.Apply</c> / <c>ConstrainedValue</c> use them: an action whose result
	/// violates a constraint is <b>rejected</b> and the entity stays as it was. Without this, every action is
	/// expected to keep the entity valid on its own (a bug otherwise), which is the right model when the
	/// methods guard themselves (<c>Order.Ship()</c>) and the wrong one when they do not (<c>BankAccount.Withdraw</c>).
	/// Enforced, a proof says "no reachable state is invalid, and every listed transition is reachable
	/// through enforced actions" — the useful part is the coverage and the diagram of the real lifecycle.
	/// </summary>
	public EntitySpec<T> Enforced()
	{
		_enforced = true;
		return this;
	}

	/// <summary>
	/// How hostile the generated data is. Starting states default to <see cref="AutoMode.Plausible"/> (they should look like real
	/// states) and action arguments to plausible values plus a few edge values (<c>""</c>, <c>-1</c>, <c>NaN</c>); this sets both.
	/// </summary>
	public EntitySpec<T> Data(AutoMode mode)
	{
		_data = mode;
		return this;
	}

	/// <summary>How a state is printed in traces and diagrams.</summary>
	public EntitySpec<T> Print(Func<T, string> print)
	{
		_print = print;
		return this;
	}

	/// <summary>"Now" for time-aware constraints. Fixed, so exploration is deterministic.</summary>
	public EntitySpec<T> Clock(DateTimeOffset now)
	{
		_clock = new FixedTimeProvider(now);
		return this;
	}

	/// <summary>"Now" from a <see cref="TimeProvider"/> you control (a <see cref="ManualTimeProvider"/> you advance between terminals).</summary>
	public EntitySpec<T> Clock(TimeProvider time)
	{
		_clock = time;
		return this;
	}

	/// <summary>Stop expanding states outside this region (in addition to <see cref="Limit"/>), so an unbounded model can still close.</summary>
	public EntitySpec<T> Boundary(Func<T, bool> inside)
	{
		_boundary = inside;
		return this;
	}

	/// <summary>States where stopping is expected (not a deadlock).</summary>
	public EntitySpec<T> Terminal(Func<T, bool> isTerminal)
	{
		_terminal = isTerminal;
		return this;
	}

	/// <summary>Must hold in at least one reachable state — proves the model can get there.</summary>
	public EntitySpec<T> Reachable(string id, Func<T, bool> holds)
	{
		_reachable.Add((id, holds));
		return this;
	}

	/// <summary>A deliberate defect for <see cref="Faults"/>: replaces the result of <paramref name="on"/> (or every action when null).</summary>
	public EntitySpec<T> Fault(string name, string? on, Func<T, T, T> perturb)
	{
		_faults.Add((name, on, perturb));
		return this;
	}

	/// <summary>
	/// Checks <paramref name="constraints"/> only on steps taken by <paramref name="action"/> — for a
	/// <c>Monotonic</c>/<c>Conserves</c> rule that holds for one action but not for the type as a whole.
	/// </summary>
	public EntitySpec<T> StepScoped(string action, ConstraintSet<T> constraints)
	{
		_scoped.Add((action, constraints));
		return this;
	}

	// ── Terminals ─────────────────────────────────────────────────────────────

	/// <summary>
	/// Proves every constraint holds in every reachable state and step. Fails with a shortest-path
	/// counterexample, and — with <paramref name="requireCoverage"/> — also when a <c>When</c> guard or
	/// an <c>Allow</c>ed transition is never exercised, since the constraint then proved nothing. With
	/// several starting states, each is explored, a rule counts as exercised if any start exercised it, and the
	/// largest report is returned.
	/// </summary>
	public SpecReport Exhaustive(
		int maxStates = 100_000,
		int maxDepth = int.MaxValue,
		bool requireCoverage = true,
		bool requireClosed = true,
		Action<string>? writeLine = null
	)
	{
		SpecReport? largest = null;
		HashSet<string>? unexercised = null;
		foreach (var start in Starts())
		{
			CheckStart(start);
			var (spec, _) = Build(start, autoFaults: false);
			var report = spec.Exhaustive(maxStates, maxDepth, writeLine: writeLine);
			if (requireClosed && !report.Closed)
			{
				throw new InvalidOperationException(
					$"The state space did not close ({report.States} states) from {_print(start)}.{Environment.NewLine}"
					+ $"Lower .Limit(...), add a .Boundary(...) (numbers that only grow need one), pass a .Key(...) that identifies equal states, or use .Sample().{Environment.NewLine}{report}"
				);
			}
			// A rule counts as exercised if any starting state exercised it: a start that is already
			// Shipped cannot take the Pending->Confirmed edge, and should not fail the whole run for it.
			var missed = report.NeverTriggered.Concat(report.NeverFired).ToHashSet();
			if (unexercised is null)
			{
				unexercised = missed;
			}
			else
			{
				unexercised.IntersectWith(missed);
			}
			if (largest is null || report.States > largest.States)
			{
				largest = report;
			}
		}
		if (requireCoverage && _actions.Count > 0 && largest!.States + largest.Pruned <= 1)
		{
			throw new VacuousPropertyException(
				$"No action changed the entity from any starting state, so nothing was explored.{Environment.NewLine}"
				+ $"Check the argument domains (.Domain / .DomainFrom) and, with .Enforced(), that the actions can succeed from the start.{Environment.NewLine}{largest}"
			);
		}
		if (requireCoverage && unexercised is { Count: > 0 })
		{
			throw new VacuousPropertyException(
				$"Every constraint held, but never exercised: {string.Join(", ", unexercised)}.{Environment.NewLine}Add actions or domain values that reach them, or pass requireCoverage: false.{Environment.NewLine}{largest}"
			);
		}
		return largest!;
	}

	/// <summary>Random walks with shrinking — for a state space too large to close.</summary>
	public SpecReport Sample(
		Action<string>? writeLine = null,
		int minSteps = 1,
		int maxSteps = 24,
		string? seed = null,
		long iter = -1,
		int time = -1,
		int threads = -1
	)
	{
		SpecReport? last = null;
		foreach (var start in Starts())
		{
			CheckStart(start);
			last = Build(start, autoFaults: false).Spec.Sample(writeLine, minSteps, maxSteps, seed, iter, time, threads);
		}
		return last!;
	}

	/// <summary>The reachable state graph, from the first starting state, as a Mermaid flowchart.</summary>
	public string Mermaid(int maxStates = 200) => Build(Starts()[0], autoFaults: false).Spec.Mermaid(maxStates);

	/// <summary>
	/// Behavioural regression guard: hashes the reachable state graph. Pass <c>0</c> the first time and
	/// the failure message shows the value to commit; it changes only when an action or a constraint
	/// changes what is reachable.
	/// </summary>
	public void Snapshot(long expected, int maxStates = 200)
	{
		var diagram = Mermaid(maxStates);
		Check.Hash(h => h.Add(diagram), expected);
	}

	/// <summary>
	/// Mutation-tests the constraints. Each declared <see cref="Fault"/> (or, when none are declared, "this
	/// action has no effect" for every action) is injected in turn; a fault no constraint catches means a
	/// constraint is missing. Throws on uncaught faults when you declared faults; with the automatic ones
	/// it only reports, since an action that legitimately changes nothing is not a gap.
	/// </summary>
	public SpecFaultsReport Faults(Action<string>? writeLine = null, int maxStates = 100_000, bool? throwOnUncaught = null)
	{
		SpecFaultsReport? last = null;
		foreach (var start in Starts())
		{
			CheckStart(start);
			last = Build(start, autoFaults: true).Spec.Faults(writeLine, maxStates, throwOnUncaught: throwOnUncaught ?? (_faults.Count > 0));
		}
		return last!;
	}

	/// <summary>Like <see cref="Faults"/>, sampled — for a state space <see cref="Exhaustive"/> cannot close.</summary>
	public SpecFaultsReport SampleFaults(Action<string>? writeLine = null, string? seed = null, long iter = -1, bool? throwOnUncaught = null)
	{
		SpecFaultsReport? last = null;
		foreach (var start in Starts())
		{
			CheckStart(start);
			last = Build(start, autoFaults: true).Spec.SampleFaults(writeLine, seed: seed, iter: iter, throwOnUncaught: throwOnUncaught ?? (_faults.Count > 0));
		}
		return last!;
	}

	/// <summary>
	/// Drives a real implementation with the same walks and, after every step, asks it whether it agrees
	/// with the entity: <paramref name="apply"/> returns null when it does, otherwise a description of the divergence.
	/// </summary>
	public SpecReport Conform<TSut>(
		Func<TSut> create,
		Func<TSut, EntityStep<T>, string?> apply,
		Action<string>? writeLine = null,
		int minSteps = 1,
		int maxSteps = 24,
		string? seed = null,
		long iter = -1,
		int time = -1,
		int threads = -1
	)
	{
		SpecReport? last = null;
		foreach (var start in Starts())
		{
			var (spec, domains) = Build(start, autoFaults: false);
			last = spec.Conform(create, (sut, t) => apply(sut, ToStep(t, domains)), writeLine, minSteps, maxSteps, seed, iter, time, threads);
		}
		return last!;
	}

	/// <summary>
	/// Shorthand for <see cref="Conform{TSut}(Func{TSut}, Func{TSut, EntityStep{T}, string}, Action{string}, int, int, string, long, int, int)"/>:
	/// <paramref name="apply"/> performs the step on the implementation, then <paramref name="agrees"/> compares it to the entity's new state.
	/// </summary>
	public SpecReport Conform<TSut>(
		Func<TSut> create,
		Action<TSut, EntityStep<T>> apply,
		Func<TSut, T, bool> agrees,
		Action<string>? writeLine = null,
		long iter = -1
	) =>
		Conform(
			create,
			(sut, step) =>
			{
				apply(sut, step);
				return agrees(sut, step.After)
					? null
					: $"implementation disagrees with the entity after {step.Action}({step.Argument}); expected {_print(step.After)}";
			},
			writeLine,
			iter: iter
		);

	/// <summary>The two actions give the same entity in either order, from every reachable state and for every argument pair.</summary>
	public void Commutes(string first, string second, long iter = -1, string? seed = null)
	{
		var (a, ia) = Find(first);
		var (b, ib) = Find(second);
		var (states, domains) = StatesAndDomains();
		var gen = Gen.Select(states, ArgGen(domains[ia]), ArgGen(domains[ib]), (s, x, y) => (s, x, y));
		gen.Sample(
			t => Same(Run(Run(t.s, a, t.x), b, t.y), Run(Run(t.s, b, t.y), a, t.x)),
			seed: seed,
			iter: iter,
			print: t => $"from {_print(t.s)}: {first}({t.x}) then {second}({t.y}) differs from the reverse order"
		);
	}

	/// <summary>Applying the action twice (same argument) gives the same entity as once, from every reachable state.</summary>
	public void Idempotent(string action, long iter = -1, string? seed = null)
	{
		var (a, ia) = Find(action);
		var (states, domains) = StatesAndDomains();
		var gen = Gen.Select(states, ArgGen(domains[ia]), (s, x) => (s, x));
		gen.Sample(
			t => Same(Run(Run(t.s, a, t.x), a, t.x), Run(t.s, a, t.x)),
			seed: seed,
			iter: iter,
			print: t => $"from {_print(t.s)}: {action}({t.x}) is not idempotent"
		);
	}

	/// <summary>
	/// A generator of entities reached by running 0 to <paramref name="maxSteps"/> generated actions from
	/// the starting states. Valid by construction (no filtering) and shrinks to the shortest action
	/// sequence — a better "give me a valid order" than filtering random ones.
	/// </summary>
	public Gen<T> States(int maxSteps = 12) => StatesAndDomains(maxSteps).States;

	// ── Internals ─────────────────────────────────────────────────────────────

	private Keyed<T> Wrap(T value) => new(value, _key);

	private bool Same(T a, T b) => Wrap(a).Equals(Wrap(b));

	private T Run(T state, ActionDef action, object? argument)
	{
		var next = action.Apply(state, argument);
		return _enforced && ConstraintProperties.ViolationsOf(_constraints, state, next, _clock).Count > 0 ? state : next;
	}

	private (ActionDef Action, int Index) Find(string name)
	{
		var index = _actions.FindIndex(a => a.Name == name);
		return index < 0
			? throw new ArgumentException($"No action named \"{name}\". Known: {string.Join(", ", _actions.Select(a => a.Name))}.", nameof(name))
			: (_actions[index], index);
	}

	private static Gen<object?> ArgGen(object[]? domain) => domain is null ? Gen.Const(() => (object?)null) : Gen.OneOfConst(domain).Select(o => (object?)o);

	private (Gen<T> States, object[]?[] Domains) StatesAndDomains(int maxSteps = 12)
	{
		var starts = Starts();
		var built = starts.Select(s => Build(s, autoFaults: false)).ToArray();
		var gens = built.Select(
			b => b.Spec.GenTrace(0, maxSteps).Select(trace => trace.Steps.Length == 0 ? trace.Initial.Value : trace.Steps[^1].After.Value)
		).ToArray();
		return (gens.Length == 1 ? gens[0] : Gen.OneOf(gens), built[0].Domains);
	}

	private static EntityStep<T> ToStep(Transition<Keyed<T>> t, object[]?[] domains) =>
		new(t.Action, t.Arg, domains[t.ActionIndex] is { } d && t.ArgIndex >= 0 && t.ArgIndex < d.Length ? d[t.ArgIndex] : null, t.Before.Value, t.After.Value);

	private List<T> Starts() => _starts ??= [.. AutoDefaults.ValidStarts(_constraints, _clock, _data ?? AutoMode.Plausible)];

	private void CheckStart(T start)
	{
		var violations = ConstraintProperties.SafeValidate(_constraints, start, _clock);
		if (violations.Count > 0)
		{
			throw new InvalidOperationException(
				$"The starting state {_print(start)} already violates: {string.Join("; ", violations.Select(v => $"{v.ConstraintId}: {v.Message}"))}"
			);
		}
	}

	private object[] DomainOf(Type type)
	{
		if (_resolved.TryGetValue(type, out var cached))
		{
			return cached;
		}
		object[] values;
		if (_domains.TryGetValue(type, out var explicitValues))
		{
			values = explicitValues;
		}
		else if (_derived.TryGetValue(type, out var derived))
		{
			values = [.. DomainOf(derived.Source).Select(derived.Project).Distinct()];
		}
		else
		{
			values = AutoDefaults.Domain(type, _data);
		}
		return _resolved[type] = values.Length > 0
			? values
			: throw new InvalidOperationException($"No values to try for {type.Name}; declare them with .Domain<{type.Name}>(...).");
	}

	private (Spec<Keyed<T>> Spec, object[]?[] Domains) Build(T start, bool autoFaults)
	{
		var spec = global::CsCheck.Spec.From(Wrap(start));
		spec.Print(s => _print(s.Value));
		// Relative to the start: a generated order that already holds three lines must still be explored,
		// so the limit is never below the start's own largest collection.
		var allowed = Math.Max(_collectionLimit, StructuralKey.LargestCollection(start));
		spec.Boundary(s => StructuralKey.LargestCollection(s.Value) <= allowed && (_boundary?.Invoke(s.Value) ?? true));
		if (_terminal is not null)
		{
			spec.Terminal(s => _terminal(s.Value));
		}

		var domains = new object[]?[_actions.Count];
		for (var i = 0; i < _actions.Count; i++)
		{
			var def = _actions[i];
			if (def.ArgumentType is null)
			{
				spec.Action(def.Name, s => Wrap(Run(s.Value, def, null)));
				continue;
			}
			var domain = def.OwnDomain ?? DomainOf(def.ArgumentType);
			domains[i] = domain;
			spec.Action(def.Name, domain, (s, a) => Wrap(Run(s.Value, def, a)));
		}

		var index = 0;
		foreach (var c in _constraints.AsConstraints())
		{
			AddRequirement(spec, c.Name ?? $"constraint{index}", c);
			index++;
		}
		foreach (var (action, set) in _scoped)
		{
			foreach (var c in set.AsConstraints())
			{
				var name = $"{c.Name ?? "constraint"}@{action}";
				spec.Rule(
					name,
					name,
					action,
					(before, after) => (c.Kind == ConstraintKind.Sequential && before.Equals(after)) || Holds(c, before.Value, after.Value)
				);
			}
		}
		foreach (var (id, holds) in _reachable)
		{
			spec.Reachable(id, id, s => holds(s.Value));
		}

		foreach (var (name, on, perturb) in _faults)
		{
			if (on is null)
			{
				spec.Fault(name, (_, _) => true, (before, after) => Wrap(perturb(before.Value, after.Value)));
			}
			else
			{
				spec.Fault(name, on, (before, after) => Wrap(perturb(before.Value, after.Value)));
			}
		}
		if (autoFaults && _faults.Count == 0)
		{
			foreach (var def in _actions)
			{
				spec.Fault($"{def.Name} has no effect", def.Name, (before, _) => before);
			}
		}
		return (spec, domains);
	}

	private bool Holds(Constraint<T> c, T before, T after) => !c.CheckAt(before, after, _clock).Any();

	private void AddRequirement(Spec<Keyed<T>> spec, string name, Constraint<T> c)
	{
		if (c.Kind == ConstraintKind.PointInTime)
		{
			if (c.Guard is { } guard)
			{
				// A When(...).Requires(...) rule: tie it to the guard so "never triggered" is visible.
				spec.Rule(name, name, (_, next) => guard(next.Value), (_, next) => Holds(c, next.Value, next.Value));
			}
			else
			{
				spec.Invariant(name, name, s => Holds(c, s.Value, s.Value));
			}
			return;
		}

		// Sequential: a step that changed nothing is a Noop and is not checked, as in ConstraintSet.Apply.
		spec.Rule(name, name, (before, after) => before.Equals(after) || Holds(c, before.Value, after.Value));
		if (c.StateOf is { } stateOf && c.Edges is { } edges)
		{
			foreach (var (from, to) in edges)
			{
				var edge = $"{name}:{from}->{to}";
				spec.Rule(edge, edge, (before, after) => stateOf(before.Value) == from && stateOf(after.Value) == to, (_, _) => true);
			}
		}
	}
